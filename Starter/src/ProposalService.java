import java.util.LinkedHashMap;
import java.util.Map;
import java.util.List;

/** D1 proposal creation and baseline eligibility checks. */
public final class ProposalService {
    // Unchanging policy that is manually updated through version updates
    private static final int POLICY_VERSION = 1;

    // The holder of current information
    private final Booking booking;
    private final Map<String, ParkingSpace> spaces;

    // This allows us to have a fresh id to increment
    private int nextId = 0; // INcrementing change in id of spaces

    // Initializing the main businesses information - setting all the final values
    public ProposalService(Booking booking, List<ParkingSpace> parkingSpaces) {
        if (booking == null || parkingSpaces == null)
            throw new IllegalArgumentException("Booking and spaces are required");
        this.booking = booking;

        LinkedHashMap<String, ParkingSpace> temp = new LinkedHashMap<String, ParkingSpace>();

        for (ParkingSpace space : parkingSpaces) {
            if (space == null){
                throw new IllegalArgumentException("Parking spaces must be non-null and have unique identifiers");
            }
            temp.put(space.id(), space);
        }

        this.spaces = temp;
    }

    // Where requests will be handled
    public Proposal propose(String targetId) {
        DomainRules.requireIdentifier(targetId);
        ParkingSpace target = spaces.get(targetId);

        //Rejection of null targets
        if (target == null)
            throw new IllegalArgumentException("Unknown parking space: " + targetId);

        if (target.id().equals(booking.spaceId()))
            throw new IllegalArgumentException("Target must differ from the current space");

        if (!target.isAvailable())
            throw new IllegalArgumentException("Parking space is not available: " + targetId);
        
        //The unique proposal identity, generated by the application
        String id = "P" + nextId++;

        //Sends a new proposal object to back to the 
        return new Proposal(id, booking.id(), target.id(), booking.version(), POLICY_VERSION, Proposal.Status.PENDING);
    }
}
